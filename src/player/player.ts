  skid = 0;              // 0..1 — насколько доска идёт боком (для спрея и звука)
  switchRide = false;    // едем «задом» — доска развёрнута хвостом вперёд
  private poseTime = 0;  // фаза покачивания рук
  private alignT = 0;    // сколько длится самовыравнивание — для разгона по s-кривой
  private sideGripSm = 1; // сглаженное сцепление на сносе: снег принимает кант не сразу
