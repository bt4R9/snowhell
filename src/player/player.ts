// становится решением, а не приговором: срезать через язык можно, если
// успеваешь выскочить. Заполняется быстро, остывает долго — поэтому две
// срезки подряд уже не пройдут.
const HEAT_UP = 2.4;    // секунд по мели до предела
const HEAT_DEEP = 3.2;  // множитель, если провалился в расплав с головой
const HEAT_COOL = 15;   // секунд полного остывания
/**
 * Секунд в расплавленной борозде до предела.
 * ★ РЕЗ ЖЖЁТ РОВНО КАК ЛАВА. Отдельная, вчетверо более жёсткая шкала (0.85 с
 * против 2.4 у расплава) делала борозду опаснее самого озера — при том, что
 * борозда стала вдвое шире и пересекать её приходится часто. Теперь это та же
 * лава: та же шкала, тот же запас на ошибку. Но рез — оружие, а не среда, и
 * по просьбе он жжёт в полтора раза быстрее расплава: 1.6 с против 2.4.
 */
// ★ И ОБРАТНО: с резом «по ходу движения» (eye.ts) борозда шириной 24 м стала
// встречаться на каждом приёме, и 1.6 с не оставляли шанса — одно пересечение
// на 20 м/с давало 0.75 шкалы, второе убивало. Пересечение должно стоить
// ~0.4: два — предел, три — смерть. Ехать ВДОЛЬ борозды по-прежнему нельзя.
const LASER_HEAT = HEAT_UP * 1.15;
/** ★ ВОДА: ниже этой скорости (м/с) доска не глиссирует и тонет; потеря хода на воде, доля/с */
const WATER_SKIM = 11;
const WATER_DRAG = 0.42;
const ROOF_CATCH = 0.9;
const RAIL_SNAP_R = 2.2;
const RAIL_FUNNEL_R = 5.5;  // радиус у въезда
const RAIL_FUNNEL_T = 0.18; // какая доля длины считается въездом
// Широкий магнит без проверки направления цеплял бы рейл при пересечении его
// поперёк. Косинус угла между ходом и линией рейла должен быть не меньше:
const RAIL_SNAP_DOT = 0.55; // ~57°
const RAIL_G = 18;          // ускорение вдоль наклонного рейла — рейл разгоняет
const GRIND_FRICTION = 0.06;
const GRIND_JUMP = 6.5;     // соскок пробелом
const GRIND_EXIT_POP = 2.0; // соскок в конце рейла
const RAIL_COOLDOWN = 0.4;  // после нормального соскока не прилипаем обратно
// СРЫВ ВЫКИДЫВАЕТ В СТОРОНУ — ту самую, в которую завалило. Так и происходит
// на самом деле: тебя не роняет вниз, а сбрасывает с бруса. Заодно это решает
// проблему повторного захвата честно, без запретов: райдер физически
// оказывается метрах в десяти от линии, и цепляться просто не за что.
// Раньше здесь были и таймер, и блокировка конкретного рейла — и то, и другое
// проигрывало: падаешь ПОД рейлом и едешь ВДОЛЬ него, так что любой запрет
// рано или поздно истекает ровно там же, где ты упал.
const RAIL_EJECT = 15;      // м/с вбок
// Выброс закрывает случай ТОЛЬКО наполовину, и это видно на замере: упав на
// нижнюю по склону сторону, райдер улетает почти на сто метров и назад уже не
// возвращается, а упав на ВЕРХНЮЮ — пролетает семь метров, тормозит о подъём
// и съезжает обратно ровно на рейл (повторный захват через 1.6 с). Поэтому
// короткая пауза всё-таки нужна — но именно короткая, как страховка, а не как
// основной механизм.
const RAIL_FALL_COOLDOWN = 2.2;
const RAIL_EJECT_UP = 4.6;  // и вверх: без воздуха бросок съедает рельеф

