import { craterDip } from './craters';
import { laserDip } from './laser';

/**
 * ★ ОДНА ТОЧКА ПРАВДЫ О ТОМ, ГДЕ ЗЕМЛЯ. Следов, которые проседают, уже два —
 * воронки от снарядов и борозды от луча, — и их будет больше. Каждый
 * потребитель (доска, камера, тень, колея) обязан вычитать ВСЕ: стоит забыть
 * один, и он поедет по старому уровню. Поэтому потребители не знают о видах
 * следа вовсе, они спрашивают только эту функцию.
 */
export function groundDip(x: number, z: number): number {
  return craterDip(x, z) + laserDip(x, z);
}
