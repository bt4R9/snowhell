/**
 * ★ ВТОРАЯ АТАКА ОКА — РЕЗ ПО ЗЕМЛЕ. Обстрел снарядами — это площадь, из
 * которой уезжают; лазер — это ЛИНИЯ, которая ходит по склону и которую надо
 * пересекать. Точка касания метёт поперёк игрока, оставляя за собой борозду с
 * расплавом: сама она проносится мимо за доли секунды, а вот след живёт
 * секунды, и именно он решает, куда можно ехать.
 *
 * ★ СЛЕД — ЦЕПОЧКА ЗВЕНЬЕВ, А НЕ ФУНКЦИЯ ОТ z. Предыдущая версия описывала
 * борозду как x(z) — по одной точке следа на каждую глубину склона. Это
 * дёшево, но накладывает жёсткое условие: луч обязан идти ВНИЗ монотонно, а
 * значит физически не может пройти поперёк курса игрока. Отсюда и брались все
 * симптомы разом — медленный, идёт параллельно, не пересекает. Здесь след
 * пишется отрезками «где был — где стал», и луч свободен ходить как угодно.
 *
 * ★ ЗВЕНЬЕВ РОВНО СТОЛЬКО, СКОЛЬКО ОПАСНО. Расплав живёт MOLTEN + COOL ≈ три
 * секунды; хранить весь восемнадцатисекундный проход незачем — кольцевой
 * буфер на MARKS звеньев покрывает последние LIFE секунд, а что старше, то уже
 * остыло и по правилам не жжёт.
 *
 * ★ ОДИН ИСТОЧНИК ПРАВДЫ. По следу едет доска, за ним проседает камера, на нём
 * лежит колея и по нему же игрок горит. Расходиться этим четверым нельзя,
 * поэтому геометрия живёт здесь, а шейдер повторяет ЭТИ ЖЕ формулы (см.
 * terrain.ts — там стоит парная пометка).
 */

import { damage, CUT_R, CUT_DEPTH, MOLTEN, COOL, CUT_LIFE } from './damage';

/** как часто ставится звено, с */
export const STAMP = 0.25;
/**
 * Полуширина борозды, м.
 * ★ РЕЗ ДОЛЖЕН ЧИТАТЬСЯ ПРЕПЯТСТВИЕМ, А НЕ ЦАРАПИНОЙ. На 140 км/ч борозда в
 * одиннадцать метров поперёк пересекается за треть секунды — её можно было
 * проскочить, даже не заметив. Полоса поражения обязана быть шире, чем
 * расстояние, которое доска проходит за время реакции.
 */
export { CUT_R, MOLTEN, COOL };
/** глубина борозды, м */
export const DEPTH = CUT_DEPTH;
/** сколько живёт звено, с */
export const LIFE = CUT_LIFE;

/**
 * ★ СЛЕД ТЕПЕРЬ — КАРТА, А НЕ КОЛЬЦО ЗВЕНЬЕВ (см. fx/damage.ts). Звено
 * вписывается в карту один раз; доска, камера, колея, урон и шейдер рельефа
 * читают одни и те же тексели. Ограничения на число звеньев нет.
 */

/** Прожечь очередное звено: от точки, где луч был, к точке, где он стал. */
export function stampCut(ax: number, az: number, bx: number, bz: number): void {
  damage.paintCut(ax, az, bx, bz);
}

/** насколько просела земля в точке — борозда от луча */
export function laserDip(x: number, z: number): number {
  return damage.cutDip(x, z);
}

/**
 * Насколько точка расплавлена: 1 — жидкая лава, 0 — застывший базальт.
 * ★ УРОН ЖИВЁТ РОВНО ЗДЕСЬ. Пока борозда светится — она жжёт; остыла —
 * это просто канава, по которой можно ехать. Иначе рез оставался бы вечной
 * стеной поперёк трассы.
 */
export function laserHeat(x: number, z: number): number {
  return damage.cutHeat(x, z);
}
