export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;   // ширина глифа + 1px просвет
export const LINE_H = 9;

export interface TextBuild {
  geo: THREE.BufferGeometry;
  width: number;  // в пикселях шрифта
  height: number;
}

/** Собирает геометрию текста (поддерживает \n); origin — левый верхний угол, y вниз */
export function buildTextGeometry(text: string, centered = false): TextBuild {
  const lines = text.toUpperCase().replace(/—/g, '-').split('\n');
  const verts: number[] = [];
  let maxW = 0;

  lines.forEach((line, li) => {
    const y0 = li * LINE_H;
    let x = 0;
    for (const ch of line) {
      const glyph = GLYPHS[ch];
      if (glyph) {
        for (let r = 0; r < GLYPH_H; r++) {
          const bits = glyph[r];
          if (!bits) continue;
          for (let c = 0; c < GLYPH_W; c++) {
            if (bits & (1 << (GLYPH_W - 1 - c))) {
              const x0 = x + c;
              const y1 = y0 + r;
              verts.push(
                x0, -y1, 0, x0 + 1, -y1, 0, x0 + 1, -(y1 + 1), 0,
                x0, -y1, 0, x0 + 1, -(y1 + 1), 0, x0, -(y1 + 1), 0
              );
            }
          }
        }
      }
      x += ADVANCE;
    }
    maxW = Math.max(maxW, Math.max(0, x - 1));
  });

  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.Float32BufferAttribute(verts, 3));
  const height = lines.length * LINE_H - (LINE_H - GLYPH_H);
  if (centered) geo.translate(-maxW / 2, height / 2, 0);
  return { geo, width: maxW, height };
}
