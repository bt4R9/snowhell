export interface EyeSpot {
  k: number;
  x: number;
  z: number;
  h: number;
}

export function eyeAt(k: number): EyeSpot {
  const n1 = noise2(k * 4.7 + 3.3, 21.1) * 0.5 + 0.5;
  const n2 = noise2(k * 6.1 - 1.7, 13.9) * 0.5 + 0.5;
  // ★ БАШНЯ СТОИТ НА ОСИ. Она не декорация сбоку: к ней едут, её видно всю
  // дорогу, и её луч ходит поперёк трассы — значит и сама она обязана быть
  // ровно по курсу.
  // ★ КООРДИНАТА СРАЗУ МИРОВАЯ. Ось трассы задана в координатах долины, а
  // сцена живёт в мировых: без перевода башня и её луч уезжали от игрока на
  // триста метров вбок (замер: пятно на −250, игрок на −535).
  const z = k * STEP + LEAD + n2 * 300;
  return { k, x: toWorldX(pisteCenterX(z), z), z, h: TOWER_H * (0.85 + n1 * 0.45) };
}

/**
 * Высота препятствия над своей землёй. У валунов она посчитана (topY), у
 * остальных выводится из масштаба: точная модель тут не нужна — важно лишь,
 * перекрывает оно луч или нет.
 */
function obstacleTop(o: { kind: string; scale: number; hMul?: number; topY?: number; r: number }): number {
  if (o.topY !== undefined) return o.topY;
  switch (o.kind) {
    case 'crag':
      return o.scale * (o.hMul ?? 1) * 0.45;
    case 'arch':
      return o.scale * 1.6;
    case 'house':
      return o.scale * 1.4;
    default:
      return o.r;
  }
}

export function eyeNear(pz: number): EyeSpot {
  const k = Math.floor(pz / STEP);
  const a = eyeAt(k);
  // ★ БАШНЯ ЖИВЁТ, ПОКА ЕЁ НЕ ПРОЕХАЛИ. Раньше переключение шло за 500 м ДО
  // неё: подъезжаешь — и око скачет на двенадцать километров вперёд, там его
  // отсекает дальность, и башня пропадает ровно в тот момент, когда она
  // ближе всего (замер: на 330 м группа visible=false, пятно застыло).
  return a.z > pz - 900 ? a : eyeAt(k + 1);
}

